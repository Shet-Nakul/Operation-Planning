// Snapshot generator: reads the current state of the live database and writes
// it to src/db/db-starter-seed/data.ts. That file is committed to the repo so a
// fresh `docker compose up` on any clone reproduces this exact dataset.
//
// Usage (from server/):
//   DATABASE_URL="postgresql://user:password@localhost:5432/hospital_scheduling?schema=public" \
//     npm run seed:generate
//
// The database must be reachable (e.g. `docker compose up postgres` is running).

import { PrismaClient } from '@prisma/client';
import { writeFileSync } from 'fs';
import { join } from 'path';
import { SEED_MODELS } from '../src/db/db-starter-seed/models';

const prisma = new PrismaClient();

async function main(): Promise<void> {
  const snapshot: Record<string, unknown[]> = {};
  let total = 0;

  for (const model of SEED_MODELS) {
    const delegate = (prisma as unknown as Record<string, { findMany: (args: unknown) => Promise<unknown[]> }>)[
      model.delegate
    ];
    const rows = await delegate.findMany({ orderBy: { id: 'asc' } });
    // Drop volatile auth/session fields so snapshots never leak live tokens.
    const sanitized = rows.map((row) => {
      const copy = { ...(row as Record<string, unknown>) };
      delete copy.refresh_token;
      return copy;
    });
    snapshot[model.key] = sanitized;
    total += sanitized.length;
    console.log(`  ${model.key}: ${sanitized.length}`);
  }

  const header =
    '/* AUTO-GENERATED by scripts/generate-starter-seed.ts — do not edit by hand.\n' +
    `   Snapshot captured ${new Date().toISOString()}. Regenerate with: npm run seed:generate */\n\n`;
  // JSON is valid as a TypeScript object literal; Date values are emitted as
  // ISO strings which Prisma accepts directly for DateTime inputs on write.
  const body = `export const snapshot: Record<string, Record<string, unknown>[]> = ${JSON.stringify(
    snapshot,
    null,
    2,
  )};\n`;

  const outPath = join(__dirname, '..', 'src', 'db', 'db-starter-seed', 'data.ts');
  writeFileSync(outPath, header + body, 'utf8');
  console.log(`\nWrote ${total} rows across ${SEED_MODELS.length} models -> ${outPath}`);
}

main()
  .catch((error) => {
    console.error(error);
    process.exitCode = 1;
  })
  .finally(() => void prisma.$disconnect());
